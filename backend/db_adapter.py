import json
import os
import sqlite3
from contextlib import contextmanager
from pathlib import Path
from urllib.parse import parse_qsl, urlencode, urlsplit, urlunsplit


DATABASE_PATH = Path(__file__).parent / "parish.db"
DATABASE_URL = os.environ.get("STJAMES_POSTGRES_URL") or os.environ.get("DATABASE_URL")


def postgres_connection_url(value):
    parts = urlsplit(value)
    query = [(key, item) for key, item in parse_qsl(parts.query) if key != "supa"]
    return urlunsplit(parts._replace(query=urlencode(query)))


class DatabaseConnection:
    def __init__(self, connection, postgres):
        self.connection = connection
        self.postgres = postgres

    def execute(self, query, parameters=()):
        return self.connection.execute(
            query.replace("?", "%s") if self.postgres else query,
            parameters,
        )

    def executemany(self, query, parameters):
        return self.connection.cursor().executemany(
            query.replace("?", "%s") if self.postgres else query,
            parameters,
        )

    def executescript(self, script):
        if self.postgres:
            for statement in script.split(";"):
                if statement.strip():
                    self.connection.execute(statement)
        else:
            self.connection.executescript(script)


@contextmanager
def get_connection():
    if DATABASE_URL:
        import psycopg
        from psycopg.rows import dict_row

        connection = psycopg.connect(
            postgres_connection_url(DATABASE_URL),
            row_factory=dict_row,
            connect_timeout=10,
            sslmode="require",
            prepare_threshold=None,
        )
        wrapped = DatabaseConnection(connection, postgres=True)
    else:
        if os.environ.get("VERCEL"):
            raise RuntimeError("A persistent Postgres URL is required on Vercel.")
        connection = sqlite3.connect(DATABASE_PATH)
        connection.row_factory = sqlite3.Row
        connection.execute("PRAGMA foreign_keys = ON")
        wrapped = DatabaseConnection(connection, postgres=False)
    try:
        yield wrapped
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def initialize_database():
    primary_key = (
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        if DATABASE_URL
        else "INTEGER PRIMARY KEY AUTOINCREMENT"
    )
    reference_type = "BIGINT" if DATABASE_URL else "INTEGER"
    timestamp_type = "TIMESTAMPTZ" if DATABASE_URL else "TEXT"
    with get_connection() as connection:
        connection.executescript(
            f"""
            CREATE TABLE IF NOT EXISTS users (
                id {primary_key}, email TEXT NOT NULL UNIQUE, name TEXT NOT NULL,
                password_hash TEXT NOT NULL,
                role TEXT NOT NULL DEFAULT 'member'
                    CHECK (role IN ('member','moderator','administrator','super_admin')),
                enabled INTEGER NOT NULL DEFAULT 1, jumuiya TEXT, ministry TEXT,
                scope_type TEXT, scope_name TEXT,
                created_at {timestamp_type} NOT NULL DEFAULT CURRENT_TIMESTAMP
            );
            CREATE TABLE IF NOT EXISTS parish_content (
                id {primary_key}, collection TEXT NOT NULL, data TEXT NOT NULL,
                created_at {timestamp_type} NOT NULL DEFAULT CURRENT_TIMESTAMP,
                updated_at {timestamp_type} NOT NULL DEFAULT CURRENT_TIMESTAMP
            );
            CREATE INDEX IF NOT EXISTS idx_content_collection ON parish_content(collection, id);
            CREATE TABLE IF NOT EXISTS settings (
                key TEXT PRIMARY KEY, value TEXT NOT NULL,
                updated_at {timestamp_type} NOT NULL DEFAULT CURRENT_TIMESTAMP
            );
            CREATE TABLE IF NOT EXISTS moderator_requests (
                id {primary_key},
                user_id {reference_type} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                scope_type TEXT NOT NULL CHECK (scope_type IN ('ministry','jumuiya')),
                scope_name TEXT NOT NULL, reason TEXT NOT NULL DEFAULT '',
                status TEXT NOT NULL DEFAULT 'pending'
                    CHECK (status IN ('pending','approved','rejected')),
                created_at {timestamp_type} NOT NULL DEFAULT CURRENT_TIMESTAMP,
                reviewed_at {timestamp_type}
            );
            CREATE TABLE IF NOT EXISTS donations (
                id {primary_key},
                user_id {reference_type} REFERENCES users(id) ON DELETE SET NULL,
                jumuiya TEXT, amount REAL NOT NULL CHECK (amount > 0),
                project TEXT, reference TEXT,
                status TEXT NOT NULL DEFAULT 'pledged'
                    CHECK (status IN ('pledged','confirmed')),
                created_at {timestamp_type} NOT NULL DEFAULT CURRENT_TIMESTAMP
            );
            CREATE TABLE IF NOT EXISTS sacramental_requests (
                id {primary_key},
                user_id {reference_type} REFERENCES users(id) ON DELETE SET NULL,
                sacrament TEXT NOT NULL, applicant_name TEXT NOT NULL, contact TEXT NOT NULL,
                details TEXT NOT NULL DEFAULT '',
                status TEXT NOT NULL DEFAULT 'pending'
                    CHECK (status IN ('pending','approved','rejected')),
                created_at {timestamp_type} NOT NULL DEFAULT CURRENT_TIMESTAMP
            );
            CREATE TABLE IF NOT EXISTS contact_messages (
                id {primary_key}, name TEXT NOT NULL, email TEXT NOT NULL,
                message TEXT NOT NULL,
                created_at {timestamp_type} NOT NULL DEFAULT CURRENT_TIMESTAMP
            );
            """
        )
        if DATABASE_URL:
            rows = connection.execute(
                "SELECT column_name FROM information_schema.columns "
                "WHERE table_schema = current_schema() AND table_name = 'users'"
            ).fetchall()
            user_columns = {row["column_name"] for row in rows}
        else:
            user_columns = {
                row["name"] for row in connection.execute("PRAGMA table_info(users)").fetchall()
            }
        for column in ("scope_type", "scope_name"):
            if column not in user_columns:
                connection.execute(f"ALTER TABLE users ADD COLUMN {column} TEXT")
        connection.execute(
            "UPDATE users SET scope_type = CASE WHEN ministry IS NOT NULL THEN 'ministry' "
            "WHEN role = 'moderator' AND jumuiya IS NOT NULL THEN 'jumuiya' END, "
            "scope_name = COALESCE(ministry, CASE WHEN role = 'moderator' THEN jumuiya END) "
            "WHERE role = 'moderator' AND scope_type IS NULL"
        )
        defaults = {
            "announcement": "",
            "payment": json.dumps(
                {
                    "paybill": "",
                    "till": "",
                    "account_name": "",
                    "bank_name": "",
                    "account_name_bank": "",
                    "account_number": "",
                    "branch": "",
                }
            ),
            "map_embed": "",
            "address": "Katheka Kai, Kenya",
            "manual_readings": "",
            "show_schedules": "true",
        }
        connection.executemany(
            "INSERT INTO settings (key, value) VALUES (?, ?) ON CONFLICT(key) DO NOTHING",
            defaults.items(),
        )
        initial = {
            "schedules": [
                {"day": "Sunday", "time": "To be announced", "type": "Sunday Worship", "visible": True},
                {"day": "Weekdays", "time": "To be announced", "type": "Weekday Mass", "visible": True},
                {"day": "Saturday", "time": "To be announced", "type": "Bible Study", "visible": True},
            ],
            "jumuiyas": [
                {
                    "name": f"Jumuiya {index}",
                    "patron": "To be announced",
                    "schedule": "To be announced",
                    "venue": "To be announced",
                    "leader": "",
                    "contact": "",
                }
                for index in range(1, 10)
            ],
            "ministries": [
                {"name": name, "description": "Information coming soon.", "moderator": ""}
                for name in ("Choir", "CWA", "CMA", "Youth", "Altar Servers", "Catechism")
            ],
            "projects": [],
            "events": [],
        }
        for collection, entries in initial.items():
            if not connection.execute(
                "SELECT 1 FROM parish_content WHERE collection = ? LIMIT 1", (collection,)
            ).fetchone():
                connection.executemany(
                    "INSERT INTO parish_content (collection, data) VALUES (?, ?)",
                    [(collection, json.dumps(item, ensure_ascii=False)) for item in entries],
                )
